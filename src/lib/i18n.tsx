const dictionaries: Record<Lang, Dict> = { uz, ru, en };

type Vars = Record<string, string | number>;
export function translate(lang: Lang, key: TKey, vars?: Vars): string {
  let text: string = dictionaries[lang][key] ?? uz[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.split(`{${k}}`).join(String(v));
  return text;
}

type I18n = {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: TKey, vars?: Vars) => string;
  /** Translate a dynamic key (e.g. `cat.${id}`); falls back to the raw value for user-entered data. */
  td: (prefix: string, value: string) => string;
  price: (value: number) => string;
};

const LOCALES: Record<Lang, string> = { uz: 'uz-UZ', ru: 'ru-RU', en: 'en-US' };
const I18nContext = createContext<I18n>(makeI18n('uz', () => {}));

function makeI18n(lang: Lang, setLang: (l: Lang) => void): I18n {
  return {
    lang,
    setLang,
    t: (key, vars) => translate(lang, key, vars),
    td: (prefix, value) => {
      const key = `${prefix}.${value}` as TKey;
      return key in uz ? translate(lang, key) : value;
    },
    price: value => new Intl.NumberFormat(LOCALES[lang]).format(value),
  };
}

export function isLang(value: unknown): value is Lang {
  return typeof value === 'string' && (LANGS as readonly string[]).includes(value);
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>('uz');

  // Read the saved/browser language after mount so server and client markup match on first render.
  useEffect(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (isLang(saved)) {
        setLangState(saved);
        return;
      }
      const browser = navigator.language.slice(0, 2).toLowerCase();
      if (isLang(browser)) setLangState(browser);
    } catch {
      /* storage may be blocked — stay on the default language */
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    try {
      localStorage.setItem(STORAGE_KEY, next);
    } catch {
      /* ignore */
    }
  }, []);

  const value = useMemo(() => makeI18n(lang, setLang), [lang, setLang]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18n {
  return useContext(I18nContext);
}
